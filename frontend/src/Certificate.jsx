import { useEffect, useRef, useState } from 'react'
import { api, DEVICE_LABELS, errorText, formatDate, formatDateTime, METHOD_LABELS } from './lib.js'

// The customer's proof. Printing uses the browser print dialog and a print
// stylesheet, which also gives "Save as PDF" without a PDF library.
// `version` changes when the pickup's devices change, so the open certificate refetches.
// `onLoaded` runs after each successful fetch: the first one issues the certificate (API-v2 4.9).
export default function Certificate({ pickupId, version, onLoaded, onClose }) {
  const [cert, setCert] = useState(null)
  const [error, setError] = useState(null)
  const heading = useRef(null)
  const focused = useRef(false)

  useEffect(() => {
    let ignore = false
    api(`/pickups/${pickupId}/certificate`)
      .then(data => { if (!ignore) { setCert(data); setError(null); onLoaded?.() } })
      // Never leave an old document (and its Print button) under an error.
      .catch(err => { if (!ignore) { setCert(null); setError(errorText(err)) } })
    return () => { ignore = true }
  }, [pickupId, version]) // eslint-disable-line react-hooks/exhaustive-deps -- onLoaded is a fresh closure each render; refetching on it would loop

  // Once it first loads (or fails), move focus here; a failure is also announced by role="alert".
  // A refetch must not pull focus away from the warehouse step that caused it.
  useEffect(() => {
    if ((cert || error) && !focused.current) {
      focused.current = true
      heading.current?.focus()
    }
  }, [cert, error])

  return (
    <section className="shell certificate-shell" aria-labelledby="cert-heading">
      <div className="core certificate">
        <h2 id="cert-heading" ref={heading} tabIndex={-1}>Certificate of data destruction</h2>
        {error && <p className="row-error" role="alert">{error}</p>}
        {!cert && !error && <p className="state">Loading certificate…</p>}

        {cert && (
          <>
            <dl className="cert-facts">
              <dt>Certificate</dt><dd>{cert.certificate_number}</dd>
              <dt>Customer</dt><dd>{cert.customer_name}</dd>
              <dt>Pickup</dt><dd>#{cert.pickup_id}, {formatDate(cert.pickup_date)}</dd>
              <dt>Standard</dt><dd>{cert.standard}</dd>
              {/* Stored when first issued, so every reprint shows the same time. */}
              <dt>Issued</dt><dd>{formatDateTime(cert.issued_at)}</dd>
              <dt>Devices</dt><dd>{cert.devices.length}</dd>
            </dl>
            <table>
              <caption className="visually-hidden">Every device received in this pickup with when it arrived and how and when its data was destroyed</caption>
              <thead>
                <tr>
                  <th scope="col">Serial number</th>
                  <th scope="col">Model</th>
                  <th scope="col">Received</th>
                  <th scope="col">Method</th>
                  <th scope="col">Sanitized</th>
                  <th scope="col">Outcome</th>
                </tr>
              </thead>
              <tbody>
                {cert.devices.map(d => (
                  <tr key={d.serial_number}>
                    <th scope="row" className="serial">{d.serial_number}</th>
                    <td data-label="Model">{d.model || 'Not recorded'}</td>
                    <td data-label="Received">{d.received_at ? formatDateTime(d.received_at) : 'Not recorded'}</td>
                    <td data-label="Method">{METHOD_LABELS[d.sanitization_method]}</td>
                    <td data-label="Sanitized">{formatDateTime(d.sanitized_at)}</td>
                    <td data-label="Outcome">{d.status === 'sanitized' ? 'Awaiting outcome' : DEVICE_LABELS[d.status]}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            {cert.not_received_serials?.length > 0 && (
              <div className="cert-exceptions">
                <h3>Listed but not received</h3>
                <p className="hint">These serials were on the booking list but never reached Revivn, so this certificate doesn't cover them.</p>
                <ul>
                  {cert.not_received_serials.map(s => <li key={s} className="serial">{s}</li>)}
                </ul>
              </div>
            )}
            <p className="hint cert-note">
              Demo document generated by Pickup Tracker. Not an official Revivn certificate.
            </p>
          </>
        )}

        <div className="detail-actions no-print">
          {cert && <button type="button" className="btn btn-primary" onClick={() => window.print()}>Print or save as PDF</button>}
          <button type="button" className="btn btn-secondary" onClick={onClose}>Close certificate</button>
        </div>
      </div>
    </section>
  )
}
